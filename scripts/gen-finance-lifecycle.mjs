// Merge into entities.ts
const entitiesFile = "src/lib/finance/entities.ts";
let content = fs.readFileSync(entitiesFile, "utf8");
const marker = "export const FIN_ENTITY_ALIASES";
const insertPos = content.indexOf(marker);
if (insertPos === -1) throw new Error("FIN_ENTITY_ALIASES not found");

let block = "";
for (const [key, cfg] of Object.entries(NEW)) {
  if (content.includes(`"${key}"`) || content.includes(`${key}:`)) continue;
  block += `  "${key}": cfg(${JSON.stringify(cfg)}),\n`;
}

// extend aliases
let aliasExtra = "";
for (const [k, v] of Object.entries(aliases)) {
  if (!content.includes(`"${k}"`)) {
    aliasExtra += `  "${k}": "${v}",\n`;
  }
}

if (block) {
  content = content.slice(0, insertPos) + block + "\n" + content.slice(insertPos);
}
if (aliasExtra) {
  content = content.replace(
    "export const FIN_ENTITY_ALIASES: Record<string, string> = {",
    `export const FIN_ENTITY_ALIASES: Record<string, string> = {\n${aliasExtra}`
  );
}
fs.writeFileSync(entitiesFile, content, "utf8");

// Generate pages
const root = path.join("src", "app", "dashboard", "finance");
const specialists = new Set([
  "cfo", "coa", "journals", "ar", "ap", "bank", "cash", "treasury", "budgets",
  "cost-centres", "costing", "assets", "tax", "approvals", "periods", "ai",
  "reports", "mobile", "engine",
]);
const all = [...Object.keys(NEW), ...Object.keys(aliases)];
let n = 0;
for (const slug of all) {
  if (specialists.has(slug)) continue;
  const key = aliases[slug] || slug;
  const dir = path.join(root, slug);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(
    path.join(dir, "page.tsx"),
    `"use client";

import { FinEntityPage } from "@/components/finance/fin-entity-page";
import { FIN_ENTITIES } from "@/lib/finance/entities";

export default function Page() {
  const config = FIN_ENTITIES["${key}"];
  if (!config) {
    return <div className="p-6 text-sm text-muted-foreground">Entity config missing: ${key}</div>;
  }
  return <FinEntityPage config={config} />;
}
`,
    "utf8"
  );
  n++;
}
