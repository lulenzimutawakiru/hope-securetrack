/**
 * Build src/lib/mes/entities.ts from production MesEntityPage configs
 * and collapse thin pages onto production/[entity].
 */
import fs from "fs";
import path from "path";

function walk(d, a = []) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p, a);
    else if (e.name === "page.tsx") a.push(p);
  }
  return a;
}

const root = path.join("src", "app", "dashboard", "production");
const pages = walk(root);
const entities = {};
const aliases = {};
const tables = new Set();

for (const pagePath of pages) {
  const c = fs.readFileSync(pagePath, "utf8");
  if (!c.includes("MesEntityPage")) continue;
  const rel = path.relative(root, path.dirname(pagePath)).replace(/\\/g, "/");
  if (!rel || rel === ".") continue;

  const title = (c.match(/title:\s*"([^"]+)"/) || [])[1];
  const description = (c.match(/description:\s*"([^"]+)"/) || [])[1];
  const table = (c.match(/table:\s*"([^"]+)"/) || [])[1];
  if (!table || !title) continue;

  tables.add(table);
  // Prefer first slug as canonical key when multiple pages share a table
  const key = table.startsWith("mes_")
    ? table.replace(/^mes_/, "").replace(/_/g, "-")
    : table.replace(/_/g, "-");

  if (!entities[key]) {
    entities[key] = {
      title,
      description: description || title,
      table,
      numberField: (c.match(/numberField:\s*"([^"]+)"/) || [])[1],
      numberPrefix: (c.match(/numberPrefix:\s*"([^"]+)"/) || [])[1],
      statusField: (c.match(/statusField:\s*"([^"]+)"/) || [])[1],
    };
  }
  if (rel !== key) aliases[rel] = key;
}

const lines = [];
lines.push(`/** Auto-generated by scripts/gen-mes-entities.mjs — MES EntityPage registry */`);
lines.push(`import type { SecureEntityConfig } from "@/components/enterprise/secure-entity-page";`);
lines.push(``);
lines.push(`export type MesEntityConfig = SecureEntityConfig;`);
lines.push(``);
lines.push(`function cfg(p: MesEntityConfig): MesEntityConfig {`);
lines.push(`  const { searchCols, columns, fields, ...rest } = p;`);
lines.push(`  return {`);
lines.push(`    ...rest,`);
lines.push(`    searchCols: searchCols ?? ["code", "name", "title", "status", "order_number", "product_name"],`);
lines.push(`    columns: columns ?? [`);
lines.push(`      { key: "code", label: "Code" },`);
lines.push(`      { key: "name", label: "Name" },`);
lines.push(`      { key: "status", label: "Status" },`);
lines.push(`      { key: "created_at", label: "Created" },`);
lines.push(`    ],`);
lines.push(`    fields: fields ?? [`);
lines.push(`      { key: "name", label: "Name", required: true },`);
lines.push(`      { key: "status", label: "Status", type: "select", options: ["draft", "active", "closed"] },`);
lines.push(`      { key: "notes", label: "Notes", type: "textarea" },`);
lines.push(`    ],`);
lines.push(`  };`);
lines.push(`}`);
lines.push(``);
lines.push(`export const MES_ENTITIES: Record<string, MesEntityConfig> = {`);
for (const [key, e] of Object.entries(entities).sort()) {
  const fields = [];
  if (e.numberField && e.numberPrefix) {
    fields.push(
      `{ key: "${e.numberField}", label: "Number", required: true, autoNumber: "${e.numberPrefix}", createOnly: true }`
    );
  }
  fields.push(`{ key: "name", label: "Name" }`);
  if (e.statusField) {
    fields.push(
      `{ key: "${e.statusField}", label: "Status", type: "select", options: ["draft", "active", "planned", "released", "closed", "cancelled"] }`
    );
  }
  fields.push(`{ key: "notes", label: "Notes", type: "textarea" }`);

  const cols = [];
  if (e.numberField) cols.push(`{ key: "${e.numberField}", label: "Number" }`);
  cols.push(`{ key: "name", label: "Name" }`);
  if (e.statusField) cols.push(`{ key: "${e.statusField}", label: "Status" }`);
  cols.push(`{ key: "created_at", label: "Created" }`);

  lines.push(`  ${JSON.stringify(key)}: cfg({`);
  lines.push(`    title: ${JSON.stringify(e.title)},`);
  lines.push(`    description: ${JSON.stringify(e.description)},`);
  lines.push(`    table: ${JSON.stringify(e.table)},`);
  if (e.numberField) lines.push(`    numberField: ${JSON.stringify(e.numberField)},`);
  if (e.numberPrefix) lines.push(`    numberPrefix: ${JSON.stringify(e.numberPrefix)},`);
  if (e.statusField) {
    lines.push(`    statusField: ${JSON.stringify(e.statusField)},`);
    lines.push(
      `    statusOptions: ["draft", "active", "planned", "released", "closed", "cancelled"],`
    );
  }
  lines.push(`    columns: [${cols.join(", ")}],`);
  lines.push(`    fields: [${fields.join(", ")}],`);
  lines.push(`  }),`);
}
lines.push(`};`);
lines.push(``);
lines.push(`export const MES_ENTITY_ALIASES: Record<string, string> = ${JSON.stringify(aliases, null, 2)};`);
lines.push(``);
lines.push(`export function resolveMesEntityConfig(slug: string): MesEntityConfig | null {`);
lines.push(`  const key = MES_ENTITY_ALIASES[slug] || slug;`);
lines.push(`  return MES_ENTITIES[key] ?? null;`);
lines.push(`}`);
lines.push(``);
lines.push(`export function listMesEntityTables(): string[] {`);
lines.push(`  return [...new Set(Object.values(MES_ENTITIES).map((c) => c.table))];`);
lines.push(`}`);
lines.push(``);

fs.mkdirSync("src/lib/mes", { recursive: true });
fs.writeFileSync("src/lib/mes/entities.ts", lines.join("\n"));
console.log("wrote mes/entities.ts keys", Object.keys(entities).length, "aliases", Object.keys(aliases).length);
console.log("tables", tables.size);
